classdef MeasurementRegistry
    %MEASUREMENTREGISTRY Registry of universal circuit measurements.
    %
    % Provides a central definition of measurements supported by the
    % universal analysis engine.
    
    properties
        Measurements
    end
    
    methods
        
        function obj = MeasurementRegistry()
            
            obj.Measurements = struct();
            
            % =========================================================
            % AC MEASUREMENTS
            % =========================================================
            
            obj = obj.register( ...
                "MaxMagnitude", ...
                "AC", ...
                "Maximum AC magnitude");
            
            obj = obj.register( ...
                "MinMagnitude", ...
                "AC", ...
                "Minimum AC magnitude");
            
            obj = obj.register( ...
                "PeakFrequency", ...
                "AC", ...
                "Frequency at maximum magnitude");
            
            obj = obj.register( ...
                "PhaseAtPeak", ...
                "AC", ...
                "Phase at maximum magnitude");
            
            obj = obj.register( ...
                "Magnitude3dB", ...
                "AC", ...
                "-3 dB magnitude level");
            
            obj = obj.register( ...
                "FLower3dB", ...
                "AC", ...
                "Lower -3 dB frequency");
            
            obj = obj.register( ...
                "FUpper3dB", ...
                "AC", ...
                "Upper -3 dB frequency");
            
            obj = obj.register( ...
                "Bandwidth3dB", ...
                "AC", ...
                "3 dB bandwidth");
            
            % =========================================================
            % DC MEASUREMENTS
            % =========================================================
            
            obj = obj.register( ...
                "MinNodeVoltage", ...
                "DC", ...
                "Minimum node voltage");
            
            obj = obj.register( ...
                "MaxNodeVoltage", ...
                "DC", ...
                "Maximum node voltage");
            
            obj = obj.register( ...
                "NodeVoltageRange", ...
                "DC", ...
                "Node voltage range");
            
            obj = obj.register( ...
                "MinBranchCurrent", ...
                "DC", ...
                "Minimum branch current");
            
            obj = obj.register( ...
                "MaxBranchCurrent", ...
                "DC", ...
                "Maximum branch current");
            
            % =========================================================
            % TRANSIENT MEASUREMENTS
            % =========================================================
            
            obj = obj.register( ...
                "StartTime", ...
                "TRAN", ...
                "Start time");
            
            obj = obj.register( ...
                "EndTime", ...
                "TRAN", ...
                "End time");
            
            obj = obj.register( ...
                "Duration", ...
                "TRAN", ...
                "Simulation duration");
            
            obj = obj.register( ...
                "PeakToPeak", ...
                "TRAN", ...
                "Peak-to-peak signal");
            
            obj = obj.register( ...
                "RMS", ...
                "TRAN", ...
                "RMS signal");
        end
        
        
        function obj = register(obj,name,analysisType,description)
            %REGISTER Add a measurement definition.
            
            name = char(name);
            
            entry = struct();
            entry.Name = string(name);
            entry.AnalysisType = string(analysisType);
            entry.Description = string(description);
            
            obj.Measurements.(name) = entry;
        end
        
        
        function tf = contains(obj,name)
            %CONTAINS Check whether a measurement exists.
            
            tf = isfield( ...
                obj.Measurements, ...
                char(name));
        end
        
        
        function entry = get(obj,name)
            %GET Retrieve a measurement definition.
            
            name = char(name);
            
            if ~isfield(obj.Measurements,name)
                
                error( ...
                    "MeasurementRegistry:UnknownMeasurement", ...
                    "Measurement '%s' is not registered.", ...
                    name);
            end
            
            entry = obj.Measurements.(name);
        end
        
        
        function names = list(obj)
            %LIST Return all registered measurement names.
            
            names = string( ...
                fieldnames(obj.Measurements));
        end
        
        
        function names = listForAnalysis(obj,analysisType)
            %LISTFORANALYSIS Return measurements for AC/DC/TRAN.
            
            names = strings(0,1);
            
            fields = fieldnames(obj.Measurements);
            
            for k = 1:numel(fields)
                
                entry = obj.Measurements.(fields{k});
                
                if strcmpi( ...
                        entry.AnalysisType, ...
                        analysisType)
                    
                    names(end+1,1) = entry.Name; %#ok<AGROW>
                end
            end
        end
    end
end