function circuit = buildOpAmp()

    circuit = createCircuit("OpAmp_NonInverting");
    circuit.Metadata.Topology = "OpAmp_NonInverting";

    % Supply
    circuit = circuitAddComponent( ...
        circuit, ...
        "VCC", ...
        "VOLTAGE_SOURCE", ...
        ["VCC","GND"], ...
        15);

    % Input
    circuit = circuitAddComponent( ...
        circuit, ...
        "VIN", ...
        "VOLTAGE_SOURCE", ...
        ["IN","GND"], ...
        1);

    % Feedback resistor
    circuit = circuitAddComponent( ...
        circuit, ...
        "RF", ...
        "R", ...
        ["OUT","NEG"], ...
        100000);

    % Ground resistor
    circuit = circuitAddComponent( ...
        circuit, ...
        "RG", ...
        "R", ...
        ["NEG","GND"], ...
        10000);

    % Op-amp
    circuit = circuitAddComponent( ...
        circuit, ...
        "U1", ...
        "OPAMP", ...
        ["IN","NEG","OUT"], ...
        [], ...
        "IdealOpAmp");

end