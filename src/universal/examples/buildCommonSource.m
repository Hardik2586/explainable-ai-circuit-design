function circuit = buildCommonSource()

    circuit = createCircuit("Common_Source");
    circuit.Metadata.Topology = "Common_Source";

    % Supply
    circuit = circuitAddComponent( ...
        circuit, ...
        "VDD", ...
        "VOLTAGE_SOURCE", ...
        ["VDD","GND"], ...
        12);

    % Input
    circuit = circuitAddComponent( ...
        circuit, ...
        "VIN", ...
        "VOLTAGE_SOURCE", ...
        ["IN","GND"], ...
        0);

    % Drain resistor
    circuit = circuitAddComponent( ...
        circuit, ...
        "RD", ...
        "R", ...
        ["VDD","DRAIN"], ...
        2200);

    % Source resistor
    circuit = circuitAddComponent( ...
        circuit, ...
        "RS", ...
        "R", ...
        ["SOURCE","GND"], ...
        1000);

    % Gate resistor
    circuit = circuitAddComponent( ...
        circuit, ...
        "RG", ...
        "R", ...
        ["VDD","GATE"], ...
        100000);

    % MOSFET
    circuit = circuitAddComponent( ...
        circuit, ...
        "M1", ...
        "MOSFET", ...
        ["DRAIN","GATE","SOURCE"], ...
        [], ...
        "2N7000");

end