
function circuit = buildRCLowPass()
% buildRCLowPass
% Universal RC low-pass circuit for AC simulation.

    % Create the circuit using the existing API
    circuit = createCircuit("RC_LowPass");

    % Set topology metadata
    circuit.Metadata.Topology = "RC_LowPass";

    % ------------------------------------------------------------
    % Input voltage source: DC 0 V, AC 1 V
    % ------------------------------------------------------------
    circuit = circuitAddComponent( ...
        circuit, ...
        "VIN", ...
        "VOLTAGE_SOURCE", ...
        ["IN","GND"], ...
        0, ...
        "");

    % Configure AC excitation
    idx = find(string({circuit.Components.Name}) == "VIN", 1);
    vin = circuit.Components(idx);
    vin.Parameters.DC = 0;
    vin.Parameters.AC = 1;
    vin.Parameters.ACPhase = 0;
    circuit.Components(idx) = vin;

    % ------------------------------------------------------------
    % Resistor: 10 kOhm
    % ------------------------------------------------------------
    circuit = circuitAddComponent( ...
        circuit, ...
        "R1", ...
        "R", ...
        ["IN","OUT"], ...
        10000, ...
        "");

    % ------------------------------------------------------------
    % Capacitor: 100 nF
    % ------------------------------------------------------------
    circuit = circuitAddComponent( ...
        circuit, ...
        "C1", ...
        "C", ...
        ["OUT","GND"], ...
        1e-7, ...
        "");

    % Validate circuit
    validation = validateCircuit(circuit);

    if ~validation.Valid
        error("buildRCLowPass:InvalidCircuit", ...
            "RC low-pass circuit validation failed.");
    end

end
