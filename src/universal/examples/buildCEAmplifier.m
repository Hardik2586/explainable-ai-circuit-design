function circuit = buildCEAmplifier()

    % ============================================================
    % CREATE CIRCUIT
    % ============================================================

    circuit = createCircuit("CE_Amplifier");

    circuit.Metadata.Topology = "CE_Amplifier";


    % ============================================================
    % SUPPLY
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "VCC", ...
        "VOLTAGE_SOURCE", ...
        ["VCC","GND"], ...
        12);

    % DC supply only.
    %
    % Value represents the DC source voltage.
    circuit = setComponentParameter( ...
        circuit, ...
        "VCC", ...
        "DC", ...
        12);


    % ============================================================
    % INPUT SOURCE
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "VIN", ...
        "VOLTAGE_SOURCE", ...
        ["IN","GND"], ...
        0);

    % Small-signal AC excitation.
    %
    % This is the critical correction:
    %
    %   DC     = 0 V
    %   AC     = 1 V
    %   ACPhase= 0 degrees
    %
    % Therefore ngspice receives:
    %
    %   VIN IN GND DC 0 AC 1
    %
    circuit = setComponentParameter( ...
        circuit, ...
        "VIN", ...
        "DC", ...
        0);

    circuit = setComponentParameter( ...
        circuit, ...
        "VIN", ...
        "AC", ...
        1);

    circuit = setComponentParameter( ...
        circuit, ...
        "VIN", ...
        "ACPhase", ...
        0);


    % ============================================================
    % BIAS NETWORK
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "R1", ...
        "R", ...
        ["VCC","BASE"], ...
        47000);

    circuit = circuitAddComponent( ...
        circuit, ...
        "R2", ...
        "R", ...
        ["BASE","GND"], ...
        10000);


    % ============================================================
    % COLLECTOR / EMITTER NETWORK
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "RC", ...
        "R", ...
        ["VCC","COLLECTOR"], ...
        2200);

    circuit = circuitAddComponent( ...
        circuit, ...
        "RE", ...
        "R", ...
        ["EMITTER","GND"], ...
        1000);


    % ============================================================
    % COUPLING CAPACITORS
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "Cin", ...
        "C", ...
        ["IN","BASE"], ...
        10e-6);

    circuit = circuitAddComponent( ...
        circuit, ...
        "Cout", ...
        "C", ...
        ["COLLECTOR","OUT"], ...
        10e-6);


    % ============================================================
    % EMITTER BYPASS
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "Ce", ...
        "C", ...
        ["EMITTER","GND"], ...
        100e-6);


    % ============================================================
    % LOAD
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "RL", ...
        "R", ...
        ["OUT","GND"], ...
        10000);


    % ============================================================
    % TRANSISTOR
    % ============================================================

    circuit = circuitAddComponent( ...
        circuit, ...
        "Q1", ...
        "BJT", ...
        ["COLLECTOR","BASE","EMITTER"], ...
        [], ...
        "2N3904");

end


%% ========================================================================
% LOCAL HELPER
% ========================================================================

function circuit = setComponentParameter( ...
    circuit, ...
    componentName, ...
    parameterName, ...
    parameterValue)

    target = string(componentName);

    for k = 1:numel(circuit.Components)

        if circuit.Components(k).Name == target

            component = circuit.Components(k);

            fieldName = char(string(parameterName));

            if ~isvarname(fieldName)
                error( ...
                    "buildCEAmplifier:InvalidParameter", ...
                    "Invalid parameter name: %s", ...
                    fieldName);
            end

            component.Parameters.(fieldName) = parameterValue;

            circuit.Components(k) = component;

            return;

        end

    end

    error( ...
        "buildCEAmplifier:ComponentNotFound", ...
        "Component %s was not found.", ...
        componentName);

end