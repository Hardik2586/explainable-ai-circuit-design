function line = componentToSpice(component)

    if ~isa(component, "Component")
        error( ...
            "componentToSpice:InvalidComponent", ...
            "Input must be a Component object.");
    end

    name  = char(component.Name);
    type  = upper(char(component.Type));
    nodes = component.Nodes;
    value = component.Value;
    model = char(component.Model);

    % ============================================================
    % BASIC VALIDATION
    % ============================================================
    if isempty(nodes)
        error( ...
            "componentToSpice:NoNodes", ...
            "Component %s has no nodes.", ...
            name);
    end

    % ============================================================
    % TRANSLATION
    % ============================================================
    switch type

        case "R"
            requireNodeCount(component, 2);
            validateNumericValue(component);
            line = sprintf( ...
                "%s %s %s %s", ...
                name, char(nodes(1)), char(nodes(2)), ...
                formatSpiceValue(value));

        case "C"
            requireNodeCount(component, 2);
            validateNumericValue(component);
            line = sprintf( ...
                "%s %s %s %s", ...
                name, char(nodes(1)), char(nodes(2)), ...
                formatSpiceValue(value));

        case "L"
            requireNodeCount(component, 2);
            validateNumericValue(component);
            line = sprintf( ...
                "%s %s %s %s", ...
                name, char(nodes(1)), char(nodes(2)), ...
                formatSpiceValue(value));

        case "VOLTAGE_SOURCE"
            requireNodeCount(component, 2);
            validateNumericValue(component);

            dcValue = getParameter(component, "DC", value);
            acValue = getParameter(component, "AC", []);
            acPhase = getParameter(component, "ACPhase", 0);

            if ~isnumeric(dcValue) || ~isscalar(dcValue) || ~isfinite(dcValue)
                error( ...
                    "componentToSpice:InvalidDC", ...
                    "Voltage source %s has an invalid DC value.", name);
            end

            line = sprintf( ...
                "%s %s %s DC %s", ...
                name, char(nodes(1)), char(nodes(2)), ...
                formatSpiceValue(dcValue));

            if ~isempty(acValue)
                if ~isnumeric(acValue) || ~isscalar(acValue) || ~isfinite(acValue)
                    error( ...
                        "componentToSpice:InvalidAC", ...
                        "Voltage source %s has an invalid AC value.", name);
                end
                if ~isnumeric(acPhase) || ~isscalar(acPhase) || ~isfinite(acPhase)
                    error( ...
                        "componentToSpice:InvalidACPhase", ...
                        "Voltage source %s has an invalid AC phase.", name);
                end

                line = sprintf( ...
                    "%s AC %s %s", ...
                    line, formatSpiceValue(acValue), ...
                    formatSpiceValue(acPhase));
            end

            waveform = getParameter(component, "Waveform", "");
            if strlength(string(waveform)) > 0
                waveform = upper(string(waveform));
                amplitude = getParameter(component, "Amplitude", []);
                frequency = getParameter(component, "Frequency", []);
                delay = getParameter(component, "Delay", 0);
                riseTime = getParameter(component, "RiseTime", []);
                fallTime = getParameter(component, "FallTime", []);

                if isempty(amplitude) || isempty(frequency)
                    error( ...
                        "componentToSpice:IncompleteWaveform", ...
                        "Voltage source %s specifies Waveform=%s but Amplitude and Frequency are required.", ...
                        name, waveform);
                end

                switch waveform
                    case "SINE"
                        if isempty(riseTime)
                            riseTime = 0;
                        end
                        if isempty(fallTime)
                            fallTime = 0;
                        end

                        % Preserve the original project's supported SIN syntax.
                        line = sprintf( ...
                            "%s SIN(%s %s %s %s %s)", ...
                            line, formatSpiceValue(dcValue), ...
                            formatSpiceValue(amplitude), ...
                            formatSpiceValue(frequency), ...
                            formatSpiceValue(delay), ...
                            formatSpiceValue(riseTime));
                        %#ok<NASGU>
                        fallTime = fallTime;

                    otherwise
                        error( ...
                            "componentToSpice:UnsupportedWaveform", ...
                            "Unsupported waveform '%s' for source %s.", ...
                            waveform, name);
                end
            end

        case "CURRENT_SOURCE"
            requireNodeCount(component, 2);
            validateNumericValue(component);

            dcValue = getParameter(component, "DC", value);
            if ~isnumeric(dcValue) || ~isscalar(dcValue) || ~isfinite(dcValue)
                error( ...
                    "componentToSpice:InvalidDC", ...
                    "Current source %s has an invalid DC value.", name);
            end

            line = sprintf( ...
                "%s %s %s DC %s", ...
                name, char(nodes(1)), char(nodes(2)), ...
                formatSpiceValue(dcValue));

            acValue = getParameter(component, "AC", []);
            acPhase = getParameter(component, "ACPhase", 0);

            if ~isempty(acValue)
                if ~isnumeric(acValue) || ~isscalar(acValue) || ~isfinite(acValue)
                    error( ...
                        "componentToSpice:InvalidAC", ...
                        "Current source %s has an invalid AC value.", name);
                end

                line = sprintf( ...
                    "%s AC %s %s", ...
                    line, formatSpiceValue(acValue), ...
                    formatSpiceValue(acPhase));
            end

        case "BJT"
            requireNodeCount(component, 3);
            if strlength(string(component.Model)) == 0
                error( ...
                    "componentToSpice:MissingModel", ...
                    "BJT %s requires a SPICE model.", name);
            end

            line = sprintf( ...
                "%s %s %s %s %s", ...
                name, char(nodes(1)), char(nodes(2)), ...
                char(nodes(3)), model);

        case "OPAMP"
            requireNodeCount(component, 3);
            if strlength(string(component.Model)) == 0
                error( ...
                    "componentToSpice:MissingModel", ...
                    "Op-amp %s requires a model identifier.", name);
            end
            if ~strcmpi(string(component.Model), "IdealOpAmp")
                error( ...
                    "componentToSpice:UnsupportedOpAmpModel", ...
                    "Unsupported op-amp model '%s'.", component.Model);
            end

            % Circuit node order: non-inverting, inverting, output.
            % E-source syntax: Ename N+ N- NC+ NC- voltage_gain.
            line = sprintf( ...
                "E_%s %s GND %s %s 1e6", ...
                name, char(nodes(3)), char(nodes(1)), char(nodes(2)));

        case "MOSFET"
            if numel(nodes) ~= 3 && numel(nodes) ~= 4
                error( ...
                    "componentToSpice:InvalidNodeCount", ...
                    "MOSFET %s requires 3 or 4 nodes in the circuit representation.", ...
                    name);
            end

            if strlength(string(component.Model)) == 0
                error( ...
                    "componentToSpice:MissingModel", ...
                    "MOSFET %s requires a SPICE model.", name);
            end

            % Optional subcircuit mode. Parameters.UseSubcircuit=true
            % emits X-device syntax for a three-terminal .SUBCKT.
            useSubcircuit = getParameter(component, "UseSubcircuit", false);
            if ~islogical(useSubcircuit) && ...
                    ~(isnumeric(useSubcircuit) && isscalar(useSubcircuit))
                error( ...
                    "componentToSpice:InvalidSubcircuitFlag", ...
                    "Parameters.UseSubcircuit must be a logical scalar.");
            end
            if ~isscalar(useSubcircuit)
                error( ...
                    "componentToSpice:InvalidSubcircuitFlag", ...
                    "Parameters.UseSubcircuit must be a logical scalar.");
            end
            useSubcircuit = logical(useSubcircuit);

            if useSubcircuit
                if numel(nodes) ~= 3
                    error( ...
                        "componentToSpice:SubcircuitNodeCount", ...
                        "MOSFET subcircuit %s requires exactly 3 nodes ordered Drain, Gate, Source.", ...
                        name);
                end

                % X-device syntax: Xname D G S subcircuit_name
                line = sprintf( ...
                    "X%s %s %s %s %s", ...
                    name, char(nodes(1)), char(nodes(2)), ...
                    char(nodes(3)), model);
            else
                % Traditional MOS syntax: Mname D G S B model.
                if numel(nodes) == 3
                    spiceNodes = [nodes, "GND"];
                else
                    spiceNodes = nodes;
                end

                line = sprintf( ...
                    "%s %s %s %s %s %s", ...
                    name, char(spiceNodes(1)), ...
                    char(spiceNodes(2)), char(spiceNodes(3)), ...
                    char(spiceNodes(4)), model);
            end

        otherwise
            error( ...
                "componentToSpice:UnsupportedType", ...
                "Unsupported component type '%s' for component '%s'.", ...
                type, name);
    end
end

%% ========================================================================
% HELPERS
% ========================================================================

function requireNodeCount(component, expected)
    actual = numel(component.Nodes);
    if actual ~= expected
        error( ...
            "componentToSpice:InvalidNodeCount", ...
            "Component %s of type %s requires %d nodes, but %d were provided.", ...
            component.Name, component.Type, expected, actual);
    end
end

function validateNumericValue(component)
    if isempty(component.Value) || ...
            ~isnumeric(component.Value) || ...
            ~isscalar(component.Value) || ...
            ~isfinite(component.Value)
        error( ...
            "componentToSpice:InvalidValue", ...
            "Component %s has an invalid numeric value.", ...
            component.Name);
    end
end

function value = getParameter(component, name, defaultValue)
    fieldName = char(string(name));
    if isstruct(component.Parameters) && isfield(component.Parameters, fieldName)
        value = component.Parameters.(fieldName);
    else
        value = defaultValue;
    end
end

function text = formatSpiceValue(value)
    text = sprintf("%.12g", value);
end
